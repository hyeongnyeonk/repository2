-- 1. [cafe_menu] 메뉴 정보 테이블 생성
-- 카페에서 판매하는 음료 목록 및 기본 가격을 관리하는 테이블입니다.
CREATE TABLE IF NOT EXISTS public.cafe_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 고유 식별자 ID
    name VARCHAR(50) NOT NULL UNIQUE,                       -- 음료 이름 (예: 카페라떼)
    price INTEGER NOT NULL CHECK (price >= 0),              -- 기본 판매 가격 (예: 4000)
    category VARCHAR(30) DEFAULT 'coffee',                  -- 카테고리 (coffee, latte, tea 등)
    is_available BOOLEAN DEFAULT true,                      -- 현재 주문 가능 여부
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()       -- 등록 일시
);

-- 2. [cafe_orders] 주문서 접수 내역 테이블 생성
-- 주문서 항목(이름, 연락처, 음료, 사이즈, 옵션, 수량, 요청사항, 결제예정금액)을 저장합니다.
CREATE TABLE IF NOT EXISTS public.cafe_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 주문 고유 번호
    customer_name VARCHAR(50) NOT NULL,                     -- 1. 주문자 이름 (필수)
    phone VARCHAR(20),                                      -- 2. 연락처 (전화번호)
    beverage VARCHAR(50) NOT NULL,                          -- 3. 선택 음료 이름 (예: 카페라떼)
    size VARCHAR(10) NOT NULL DEFAULT 'M',                  -- 4. 사이즈 (S, M, L)
    options TEXT[] DEFAULT '{}',                            -- 5. 추가 옵션 목록 (배열: 샷 추가, 크림 추가 등)
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity >= 1 AND quantity <= 10), -- 6. 수량 (1~10)
    requests TEXT,                                          -- 7. 고객 요청사항 (textarea)
    total_price INTEGER NOT NULL CHECK (total_price >= 0),  -- 계산된 총 주문 금액
    order_status VARCHAR(20) DEFAULT '접수완료',            -- 주문 상태 (접수완료, 제조중, 픽업대기, 완료)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()       -- 주문 접수 일시
);

-- RLS (Row Level Security) 설정 (Supabase 권한 제어)
ALTER TABLE public.cafe_menu ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cafe_orders ENABLE ROW LEVEL SECURITY;

-- 모든 사용자(익명 포함)가 메뉴를 조회할 수 있도록 정책 생성
CREATE POLICY "Allow public read access for cafe_menu" 
ON public.cafe_menu FOR SELECT USING (true);

-- 모든 사용자(익명 포함)가 주문을 등록(INSERT)할 수 있도록 정책 생성
CREATE POLICY "Allow public insert for cafe_orders" 
ON public.cafe_orders FOR INSERT WITH CHECK (true);

-- 모든 사용자(익명 포함)가 주문 내역을 조회할 수 있도록 정책 생성 (필요 시 수정 가능)
CREATE POLICY "Allow public read access for cafe_orders" 
ON public.cafe_orders FOR SELECT USING (true);


